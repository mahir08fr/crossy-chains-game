import { riverRulesVersion, riverRockBoxes, difficultyAt, sectionStart, generatedSettings, sectionIndex, sectionCenter, generatorVersion, roadLanes, generateSection, sectionBoxes, streamingSettings, railwaySettings, riverSettings, settings } from '@crossy/config';
import type { CourseBox, GroupSize, PlayerId, Point3, WorldSection } from '@crossy/config';
import { RoadChallenge } from './road.js';
import { RailwayChallenge } from './railway.js';
import { RiverChallenge, inRiver } from './river.js';
import type { RiverPlayer } from './river.js';

type Pose = { id: PlayerId; position: Point3 };
export class GeneratedWorld {
  private readonly active = new Map<number, { section: WorldSection; handles: number[]; road?: RoadChallenge; railway?: RailwayChallenge }>();
  private time = 0;
  private created = 0;
  private removed = 0;
  private removedColliders = 0;
  private highWater = 0;
  private rearLimit = -6.7;
  /** Slowest physical body advances progress. Move only through verified empty space. */
  progress(points: readonly Point3[], dt: number): number {
    if(this.ended)return this.rearLimit;
    const min=Math.min(...points.map(p=>p.z));
    this.highWater=Math.max(this.highWater,min,0);
    const desired=Math.min(this.highWater-generatedSettings.rearDistance,min-generatedSettings.rearClearance);
    this.rearLimit=Math.max(this.rearLimit,Math.min(desired,this.rearLimit+generatedSettings.rearSpeed*dt));
    return this.rearLimit;
  }
  private readonly water: RiverChallenge;
  private dead: PlayerId[] = [];
  constructor(readonly seed: number, private readonly capacity: GroupSize, ids: PlayerId[],
    private readonly add: (box: CourseBox) => number, private readonly remove: (handle: number) => void) {
    this.water = new RiverChallenge(ids, p => this.wet(p), p => this.safe(p), Infinity);
  }
  get ended(): boolean { return this.dead.length > 0; }
  private volumes() { return [...this.active.values()].filter(a => a.section.type === 'river').map(({section:s}) => ({minZ:sectionCenter(s)-2.5,maxZ:sectionCenter(s)+2.5,halfWidth:s.halfWidth})); }
  wet(p: Point3): boolean { return this.volumes().some(v => inRiver(p,v)); }
  current(p: Point3): number {
    for(const {section:s} of this.active.values())if(s.river && inRiver(p,{minZ:sectionCenter(s)-2.5,maxZ:sectionCenter(s)+2.5,halfWidth:s.halfWidth}))return s.river.direction*s.river.acceleration;
    return 0;
  }
  private safe(p: RiverPlayer): boolean {
    const margin = settings.player.radius + riverSettings.safeMargin;
    return p.grounded && Math.abs(p.position.x) <= 10 - margin
      && p.position.y - settings.player.halfHeight - settings.player.radius >= -.05
      && !this.volumes().some(v => p.position.z + margin >= v.minZ && p.position.z - margin <= v.maxZ);
  }
  /** Extent includes EVERY player and cable body; margin exceeds their shapes and contact skin.
   * No history accumulates. Behind sections are regenerated by index on retreat. */
  stream(points: readonly Point3[]): void {
    const min = Math.min(...points.map(p=>p.z)) - streamingSettings.contactMargin;
    const max = Math.max(...points.map(p=>p.z)) + streamingSettings.contactMargin;
    const first = Math.max(0, sectionIndex(min - streamingSettings.behind));
    const last = Math.max(0, sectionIndex(max + streamingSettings.ahead));
    for (const [index,a] of this.active) if(index < first || index > last) {
      for(const handle of a.handles) this.remove(handle);
      this.removed++; this.removedColliders += a.handles.length;
      this.active.delete(index);
    }
    for(let index=first;index<=last;index++) if(!this.active.has(index)) {
      const section=generateSection(this.seed,index,this.capacity,undefined,difficultyAt(sectionStart(index))), center=sectionCenter(section);
      const road = section.type === 'road' ? new RoadChallenge(roadLanes(section),1,Infinity,this.time) : undefined;
      const railway = section.type === 'railway' ? new RailwayChallenge({ ...railwaySettings,z:center,finishZ:Infinity,safeSeconds:section.safeSeconds,direction:section.direction },this.time) : undefined;
      // Clock is world-owned, including time spent unloaded; recreation is deterministic.
      this.created++;
      this.active.set(index,{section,handles:[...sectionBoxes(section),...(section.river?riverRockBoxes(section.river):[])].map(this.add),road,railway});
    }
  }
  step(before: Pose[], after: (Pose & {grounded:boolean})[], dt: number): void {
    if(this.ended)return;
    for(const a of this.active.values()) { a.road?.step(before,after,dt); a.railway?.step(before,after,dt); }
    this.water.step(after,dt); this.time+=dt;
    // Active challenges have no victims; avoid serializing every pooled vehicle per substep.
    this.dead=[...new Set([...this.active.values()].flatMap(a=>[...(a.road?.ended?a.road.state().dead:[]),...(a.railway?.ended?a.railway.state().dead:[])]).concat(this.water.state().dead))].sort();
  }
  diagnostics() {
    return { activeSections: this.active.size, createdSections: this.created, removedSections: this.removed, removedTerrainColliders: this.removedColliders };
  }
  state() {
    return { highWater:this.highWater,rearLimit:this.rearLimit,version:generatorVersion,riverVersion:riverRulesVersion,seed:this.seed,elapsedSeconds:this.time,sections:[...this.active.values()].sort((a,b)=>a.section.index-b.section.index).map(a=>({...a.section,...(a.section.river?{river:{...a.section.river,rocks:a.section.river.rocks.map(r=>({...r}))}}:{})})),
      hazards:[...this.active.values()].filter(a=>a.road||a.railway).sort((a,b)=>a.section.index-b.section.index).map(a=>({id:a.section.id,...(a.road?{road:a.road.state()}:{}),...(a.railway?{railway:a.railway.state()}:{} )})),
      water:this.water.state(),dead:[...this.dead],outcome:this.ended?'failed' as const:'active' as const };
  }
}
